// Puts the catalog rows in a manifest into a server's dataassets, through its POST /syncAsset (the web service's, as the
// TS server's dataAssetSync.ts did: an upsert by assetPath that bumps the CRC, so the hiss picks the rows up). Run from
// the repository root, with the server's public URL (the router sends /syncAsset to web):
//
//   DATA_ASSET_TOKEN=<the server's DATA_ASSET_TOKEN> node dotnet/tools/assets/sync_assets.mjs <serverUrl> [manifest] [--apply]
//
// Without --apply it only lists what it would send. With --bash instead of a URL it writes sync_assets.sh beside the
// manifest: the same requests as a bash script that needs only curl, for a host without node.
//
//   node dotnet/tools/assets/sync_assets.mjs --bash [manifest]
//
// The manifest defaults to end-game-assets.json beside this file: every catalog row the End Game update needs (its battle pass, Fighter Passes, Chromium and other OVS skins, emotes,
// profile icons, taunts, announcer pack and badge, with the game's unreleased cosmetics in the pass) and the OVS mutators
// (Individual Stocks, Friendly Fire, Beta Speed, and Shield HP from the experimental pak), each
// { slug, assetType, assetPath, character_slug } as tested in game. Every row is sent enabled.
import fs from "node:fs";
import path from "node:path";

const args = process.argv.slice(2);
const apply = args.includes("--apply");
const bash = args.includes("--bash");
const positional = args.filter((a) => a !== "--apply" && a !== "--bash");
// --bash takes no URL: its only argument is the manifest.
const [baseUrl, manifestArg] = bash ? [undefined, positional[0]] : positional;
if (!baseUrl && !bash) {
  console.error("usage: DATA_ASSET_TOKEN=... node dotnet/tools/assets/sync_assets.mjs <serverUrl> [manifest] [--apply]\n" +
    "       node dotnet/tools/assets/sync_assets.mjs --bash [manifest]   (writes sync_assets.sh beside the manifest)");
  process.exit(2);
}
const token = process.env.DATA_ASSET_TOKEN;
if (apply && !token) {
  console.error("DATA_ASSET_TOKEN is required with --apply");
  process.exit(2);
}

const manifest = manifestArg ?? path.join(path.dirname(new URL(import.meta.url).pathname.replace(/^\/([A-Za-z]:)/, "$1")), "end-game-assets.json");
const rows = JSON.parse(fs.readFileSync(manifest, "utf8"));
const fields = ["slug", "assetType", "assetPath", "character_slug"];
for (const row of rows) {
  for (const field of fields) {
    if (typeof row[field] !== "string" || (field !== "character_slug" && row[field] === "")) {
      throw new Error(`${manifest}: ${JSON.stringify(row)} has no ${field}`);
    }
  }
}
const paths = new Set(rows.map((r) => r.assetPath));
if (paths.size !== rows.length) throw new Error(`${manifest}: an assetPath appears twice`);

if (bash) {
  // The same requests as a bash script that needs only curl (no node on the server), the URL and token from the
  // environment so the file holds no secret. Single quotes in a value are closed, escaped and reopened.
  const q = (s) => `'${s.replaceAll("'", "'\\''")}'`;
  const out = path.join(path.dirname(manifest), "sync_assets.sh");
  const lines = [
    "#!/usr/bin/env bash",
    `# Generated by sync_assets.mjs --bash from ${path.basename(manifest)} (${rows.length} rows): regenerate it, don't edit it.`,
    "# Puts the catalog rows into a server's dataassets through its POST /syncAsset (web), as sync_assets.mjs does, with",
    "# only curl. Without --apply it lists what it would send:",
    "#",
    "#   DATA_ASSET_TOKEN=<the server's DATA_ASSET_TOKEN> OVS_URL=<serverUrl> bash sync_assets.sh [--apply]",
    "set -u",
    ': "${OVS_URL:?set OVS_URL to the server URL}"',
    'apply=0; [ "${1:-}" = "--apply" ] && apply=1',
    'if [ "$apply" = 1 ]; then : "${DATA_ASSET_TOKEN:?DATA_ASSET_TOKEN is required with --apply}"; fi',
    'url="${OVS_URL%/}/syncAsset"',
    "failed=0",
    "row() { # slug, JSON body",
    '  if [ "$apply" = 0 ]; then printf "  %s\\n" "$1"; return; fi',
    "  status=$(curl -sS -o /dev/null -w '%{http_code}' -X POST \"$url\" -H 'content-type: application/json' \\",
    '    -H "authorization: Bearer $DATA_ASSET_TOKEN" --data-binary "$2") || status=000',
    '  [ "$status" = 200 ] || failed=$((failed + 1))',
    '  printf "  %s %s\\n" "$status" "$1"',
    "}",
    `echo "${rows.length} rows -> $url$( [ "$apply" = 1 ] || echo ' (dry run: add --apply to send)')"`,
    ...rows.map((r) => `row ${q(r.slug)} ${q(JSON.stringify({ slug: r.slug, assetType: r.assetType, assetPath: r.assetPath, character_slug: r.character_slug, enabled: true }))}`),
    `if [ "$apply" = 1 ]; then [ "$failed" = 0 ] && echo "all ${rows.length} synced" || echo "$failed of ${rows.length} failed"; fi`,
    '[ "$failed" = 0 ]',
    "",
  ];
  fs.writeFileSync(out, lines.join("\n"));
  console.log(`wrote ${out}: ${rows.length} rows`);
  process.exit(0);
}

console.log(`${rows.length} rows from ${manifest} -> ${baseUrl}/syncAsset${apply ? "" : " (dry run: add --apply to send)"}`);
let failed = 0;
for (const row of rows) {
  const body = { slug: row.slug, assetType: row.assetType, assetPath: row.assetPath, character_slug: row.character_slug, enabled: true };
  if (!apply) {
    console.log(`  ${row.assetType.padEnd(22)} ${row.slug}`);
    continue;
  }
  const res = await fetch(`${baseUrl.replace(/\/$/, "")}/syncAsset`, {
    method: "POST",
    headers: { "content-type": "application/json", authorization: `Bearer ${token}` },
    body: JSON.stringify(body),
  });
  if (res.status !== 200) failed++;
  console.log(`  ${res.status} ${row.slug}`);
}
if (apply) console.log(failed ? `${failed} of ${rows.length} failed` : `all ${rows.length} synced`);
process.exit(failed ? 1 : 0);
